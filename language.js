  const originalNodes = new WeakMap();
  const originalAttributes = new WeakMap();
  let originalTitle;

  function normalize(value) {
    return value.replace(/\s+/g, " ").trim();
  }

  function translateText(lang) {
    const walker = document.createTreeWalker(
      document.body,
      NodeFilter.SHOW_TEXT,
      {
        acceptNode(node) {
          if (!node.nodeValue || !normalize(node.nodeValue)) return NodeFilter.FILTER_REJECT;
          const parent = node.parentElement;
          if (!parent || /^(SCRIPT|STYLE|NOSCRIPT|CODE|PRE)$/i.test(parent.tagName)) return NodeFilter.FILTER_REJECT;
          return NodeFilter.FILTER_ACCEPT;
        }
      }
    );

    let node;
    while ((node = walker.nextNode())) {
      if (!originalNodes.has(node)) originalNodes.set(node, node.nodeValue);
      const original = originalNodes.get(node);
      if (lang === "tr") {
        node.nodeValue = original;
        continue;
      }

      const key = normalize(original);
      if (translations[key]) {
        const leading = original.match(/^\s*/)?.[0] || "";
        const trailing = original.match(/\s*$/)?.[0] || "";
        node.nodeValue = leading + translations[key] + trailing;
      }
    }
  }

  function translateAttributes(lang) {
    const elements = document.querySelectorAll("[alt], [title], [aria-label], input[placeholder]");
    elements.forEach((el) => {
      ["alt", "title", "aria-label", "placeholder"].forEach((attr) => {
        if (!el.hasAttribute(attr)) return;
        const storeKey = attr;
        let originals = originalAttributes.get(el);
        if (!originals) {
          originals = {};
          originalAttributes.set(el, originals);
        }
        if (!(storeKey in originals)) originals[storeKey] = el.getAttribute(attr);
        const original = originals[storeKey];
        if (lang === "tr") {
          el.setAttribute(attr, original);
        } else if (attributeTranslations[original]) {
          el.setAttribute(attr, attributeTranslations[original]);
        }
      });
    });
  }

  function setLanguage(lang) {
    if (!["tr", "en"].includes(lang)) lang = "tr";
    document.documentElement.lang = lang;
    translateText(lang);
    translateAttributes(lang);

    if (originalTitle === undefined) originalTitle = document.title;
    if (lang === "tr") {
      document.title = originalTitle;
    } else {
      document.title = translations[originalTitle] || originalTitle;
    }

    document.querySelectorAll("[data-set-lang]").forEach((button) => {
      button.setAttribute("aria-pressed", String(button.dataset.setLang === lang));
    });

    try {
      localStorage.setItem("ieeekhas-language", lang);
    } catch (_) {}
  }

  function init() {
    document.querySelectorAll("[data-set-lang]").forEach((button) => {
      button.addEventListener("click", () => setLanguage(button.dataset.setLang));
    });

    let lang = "tr";
    try {
      lang = localStorage.getItem("ieeekhas-language") || "tr";
    } catch (_) {}
    setLanguage(lang);
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", init);
  } else {
    init();
  }
